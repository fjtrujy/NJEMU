/******************************************************************************

	psvita_shaders.h

	Shaders shared by the PS Vita video backends (vitaGL and vita2d/GXM).

	The GXP blobs are the output of SceShaccCg for the Cg sources below,
	embedded so neither backend needs libshacccg.suprx at runtime.  To
	regenerate them after editing a source: build the vitaGL backend with
	PSVITA_GL_SHADER_SOURCE=1, run it once (Vita3K is fine), take the files
	from ux0:data/shader_cache/<TITLEID>/v2/{v,f}/, strip the vitaGL header
	(everything before "GXP\0") and convert them with xxd -i.

******************************************************************************/

