/******************************************************************************

	psvita_shaders.h

	Shaders shared by the PS Vita video backends (vitaGL and vita2d/GXM).

	The GXP blobs are the output of SceShaccCg for the Cg sources below,
	embedded so neither backend needs libshacccg.suprx at runtime.  To
	regenerate them after editing a source: build with
	-DCMAKE_C_FLAGS=-DPSVITA_GL_SHADER_SOURCE=1, run it once with the vitaGL
	backend (Vita3K is fine), take ux0:data/njemu_shaders/NN.bin (vertex,
	indexed, indexed depth, direct, then the filters, in that order), strip
	the vitaGL header (everything before "GXP\0") and the padding after the
	size the GXP header records at offset 8, and convert them with xxd -i.

******************************************************************************/

