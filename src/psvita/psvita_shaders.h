#define PSVITA_SHADERS_H

#include <stdint.h>

__attribute__((unused))
static const char psvita_shader_vertex_cg[] =
	"void main(\n"
	"	float2 aUV,\n"
	"	float2 aPos,\n"
	"	float2 aZP,\n"
	"	uniform float4 uRowX,\n"
	"	uniform float4 uRowY,\n"
	"	uniform float4 uTexScale,\n"
	"	float4 out gl_Position : POSITION,\n"
	"	float2 out vUV : TEXCOORD0,\n"
	"	float out vPal : TEXCOORD1)\n"
	"{\n"
	"	float3 p = float3(aPos, 1.0);\n"
	"	gl_Position = float4(dot(uRowX.xyz, p), dot(uRowY.xyz, p),\n"
	"	                     aZP.x * (2.0 / 65535.0) - 1.0, 1.0);\n"
	"	vUV = aUV * uTexScale.xy;\n"
	"	vPal = (aZP.y + 0.5) * uTexScale.z;\n"
	"}\n";

__attribute__((unused))
static const char psvita_shader_indexed_cg[] =
	"float4 main(float2 vUV : TEXCOORD0, float vPal : TEXCOORD1,\n"
	"	uniform sampler2D uTex : TEXUNIT0,\n"
	"	uniform sampler2D uClut : TEXUNIT1) : COLOR\n"
	"{\n"
	"	float i = tex2D(uTex, vUV).x;\n"
	"	return tex2D(uClut, float2(i * (255.0 / 256.0) + (0.5 / 256.0), vPal));\n"
	"}\n";

__attribute__((unused))
static const char psvita_shader_indexed_depth_cg[] =
	"float4 main(float2 vUV : TEXCOORD0, float vPal : TEXCOORD1,\n"
	"	uniform sampler2D uTex : TEXUNIT0,\n"
	"	uniform sampler2D uClut : TEXUNIT1) : COLOR\n"
	"{\n"
	"	float i = tex2D(uTex, vUV).x;\n"
	"	float4 c = tex2D(uClut, float2(i * (255.0 / 256.0) + (0.5 / 256.0), vPal));\n"
	"	if (c.w > 0.5)\n"
	"		discard;\n"
	"	return c;\n"
	"}\n";

__attribute__((unused))
static const char psvita_shader_direct_cg[] =
	"float4 main(float2 vUV : TEXCOORD0,\n"
	"	uniform sampler2D uTex : TEXUNIT0) : COLOR\n"
	"{\n"
	"	return tex2D(uTex, vUV);\n"
	"}\n";

/*
 * Presentation filters (VIDEO_FILTER_*), drawn by the sharp bilinear pass:
 * the CRT, CRT Bleeding and CRT Bleeding Flat PostFX shaders by Rinnegatamante
 * (https://github.com/Rinnegatamante/PCSX_AwO, assets/postfx), based on
 * Mattias Gustavsson's CRT shader (https://www.shadertoy.com/view/Ms23DR), as
 * tuned for FF3 Vita.  They read the shared vertex shader's normalised vUV;
 * uOutputSize is the destination size in display pixels, iTime in seconds.
 */
__attribute__((unused))
static const char psvita_shader_crt_cg[] =
	"float2 curve(float2 uv)\n"
	"{\n"
	"	float2 p = (uv - 0.5) * 2.2;\n"
	"	p.x *= 1.0 + 0.04 * p.y * p.y;\n"
	"	p.y *= 1.0 + 0.0625 * p.x * p.x;\n"
	"	return p * 0.46 + 0.5;\n"
	"}\n"
	"float4 main(float2 vTexcoord : TEXCOORD0, float2 screenPosition : WPOS,\n"
	"	uniform sampler2D uTex : TEXUNIT0,\n"
	"	uniform float iTime, uniform float2 uOutputSize) : COLOR\n"
	"{\n"
	"	float2 uv = curve(vTexcoord);\n"
	"	float3 center = tex2D(uTex, uv).rgb;\n"
	"	float3 shifted = tex2D(uTex, uv + float2(0.0015, -0.0010)).rgb;\n"
	"	float3 col = float3(shifted.r, center.g, center.b) * 1.065 + 0.05;\n"
	"	col = saturate(col * (0.6 + 0.4 * col));\n"
	"	float vig = max(16.0 * uv.x * uv.y * (1.0 - uv.x) * (1.0 - uv.y), 0.0);\n"
	"	float vignetting = sqrt(sqrt(vig));\n"
	"	float linePhase = abs(frac(uv.y * uOutputSize.y * 0.2387324146 + 0.25 * iTime) - 0.5);\n"
	"	float scanline = 0.38 + 0.8 * linePhase;\n"
	"	short pixelX = (short)floor(screenPosition.x);\n"
	"	float mask = 1.0 - 0.65 * (float)(pixelX & 1);\n"
	"	float valid = step(0.0, uv.x) * step(uv.x, 1.0) * step(0.0, uv.y) * step(uv.y, 1.0);\n"
	"	col *= vignetting * scanline * mask * valid * 2.8;\n"
	"	return float4(col * float3(0.95, 1.05, 0.95), 1.0);\n"
	"}\n";

__attribute__((unused))
static const char psvita_shader_crt_bleeding_cg[] =
	"float2 curve(float2 uv)\n"
	"{\n"
	"	float2 p = (uv - 0.5) * 2.2;\n"
	"	p.x *= 1.0 + 0.04 * p.y * p.y;\n"
	"	p.y *= 1.0 + 0.0625 * p.x * p.x;\n"
	"	return p * 0.46 + 0.5;\n"
	"}\n"
	"float4 main(float2 vTexcoord : TEXCOORD0, float2 screenPosition : WPOS,\n"
	"	uniform sampler2D uTex : TEXUNIT0,\n"
	"	uniform float iTime, uniform float2 uOutputSize) : COLOR\n"
	"{\n"
	"	float2 uv = curve(vTexcoord);\n"
	"	float3 center = tex2D(uTex, uv).rgb;\n"
	"	float2 texel = 1.0 / uOutputSize;\n"
	"	float2 bleedOffset = float2(2.0 * texel.x, 0.0);\n"
	"	float2 bleedMin = 0.5 * texel;\n"
	"	float2 bleedMax = 1.0 - 0.5 * texel;\n"
	"	float3 left = tex2D(uTex, clamp(uv - bleedOffset, bleedMin, bleedMax)).rgb;\n"
	"	float3 right = tex2D(uTex, clamp(uv + bleedOffset, bleedMin, bleedMax)).rgb;\n"
	"	float3 bleed = lerp(center, 0.5 * (left + right), 0.42);\n"
	"	bleed += dot(center - bleed, float3(0.299, 0.587, 0.114));\n"
	"	float3 col = bleed * 1.065 + 0.05;\n"
	"	col = saturate(col * (0.6 + 0.4 * col));\n"
	"	float vig = max(16.0 * uv.x * uv.y * (1.0 - uv.x) * (1.0 - uv.y), 0.0);\n"
	"	float vignetting = sqrt(sqrt(vig));\n"
	"	float linePhase = abs(frac(uv.y * uOutputSize.y * 0.2387324146 + 0.25 * iTime) - 0.5);\n"
	"	float scanline = 0.38 + 0.8 * linePhase;\n"
	"	short pixelX = (short)floor(screenPosition.x);\n"
	"	float mask = 1.0 - 0.65 * (float)(pixelX & 1);\n"
	"	float valid = step(0.0, uv.x) * step(uv.x, 1.0) * step(0.0, uv.y) * step(uv.y, 1.0);\n"
	"	col *= vignetting * scanline * mask * valid * 2.8;\n"
	"	return float4(col * float3(0.95, 1.05, 0.95), 1.0);\n"
	"}\n";

__attribute__((unused))
static const char psvita_shader_crt_bleeding_flat_cg[] =
	"float4 main(float2 vTexcoord : TEXCOORD0, float2 screenPosition : WPOS,\n"
	"	uniform sampler2D uTex : TEXUNIT0,\n"
	"	uniform float2 uOutputSize) : COLOR\n"
	"{\n"
	"	float2 uv = vTexcoord;\n"
	"	float3 center = tex2D(uTex, uv).rgb;\n"
	"	float2 texel = 1.0 / uOutputSize;\n"
	"	float2 bleedOffset = float2(2.0 * texel.x, 0.0);\n"
	"	float2 bleedMin = 0.5 * texel;\n"
	"	float2 bleedMax = 1.0 - 0.5 * texel;\n"
	"	float3 left = tex2D(uTex, clamp(uv - bleedOffset, bleedMin, bleedMax)).rgb;\n"
	"	float3 right = tex2D(uTex, clamp(uv + bleedOffset, bleedMin, bleedMax)).rgb;\n"
	"	float3 bleed = lerp(center, 0.5 * (left + right), 0.42);\n"
	"	bleed += dot(center - bleed, float3(0.299, 0.587, 0.114));\n"
	"	float3 col = bleed * 1.065 + 0.05;\n"
	"	col = saturate(col * (0.6 + 0.4 * col));\n"
	"	float linePhase = abs(frac(uv.y * uOutputSize.y * 0.2387324146) - 0.5);\n"
	"	float scanline = 0.38 + 0.8 * linePhase;\n"
	"	short pixelX = (short)floor(screenPosition.x);\n"
	"	float mask = 1.0 - 0.65 * (float)(pixelX & 1);\n"
	"	col *= scanline * mask * 2.5;\n"
	"	return float4(col * float3(0.95, 1.05, 0.95), 1.0);\n"
	"}\n";

