static int extra_index(uint16_t code)
{
    return code >= ICON_VIDEO && code <= ICON_TOOLS ? (int)(code - ICON_VIDEO) : -1;
}

int menu_icon_small_get(struct font_t *font, uint16_t code, int light)
{
    int index = extra_index(code);
    if (index < 0) return 0;
    font->data = light ? menu_s_light[index] : menu_s_pixels[index];
    font->width = light ? 32 : 24;
    font->height = light ? 26 : 18;
    font->pitch = 32;
    font->skipx = 0;
    font->skipy = 0;
    return 1;
}

int menu_icon_large_get(struct font_t *font, uint16_t code, int light)
{
    int index = extra_index(code);
    if (index < 0) return 0;
    font->data = light ? menu_l_light[index] : menu_l_pixels[index];
    font->width = light ? 40 : 32;
    font->height = light ? 32 : 24;
    font->pitch = 32;
    font->skipx = 0;
    font->skipy = 0;
    return 1;
}
